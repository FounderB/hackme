#!/usr/bin/env bash
# Refresh Cloudflare IP lists and install nginx geo map on the hub.
# Safe default: write map + conf.d include only.
# Set APPLY_VHOSTS=1 to insert the deny-non-CF include into public :443 vhosts.
#
#   NODE_SSH=hackme-vps bash scripts/ops/apply_cloudflare_origin_guard.sh
#   NODE_SSH=hackme-vps APPLY_VHOSTS=1 bash scripts/ops/apply_cloudflare_origin_guard.sh
set -euo pipefail
NODE_SSH="${NODE_SSH:-hackme-vps}"
APPLY_VHOSTS="${APPLY_VHOSTS:-0}"
DRY_RUN="${DRY_RUN:-0}"
ROOT="$(cd "$(dirname "$0")/../.." && pwd)"

ssh -o BatchMode=yes -o ConnectTimeout=25 "$NODE_SSH" \
  "APPLY_VHOSTS=${APPLY_VHOSTS} DRY_RUN=${DRY_RUN} bash -s" <<'REMOTE'
set -euo pipefail
SNIP=/etc/nginx/snippets
sudo mkdir -p "$SNIP"
TMP=$(mktemp -d)
trap 'rm -rf "$TMP"' EXIT
curl -fsSL https://www.cloudflare.com/ips-v4 -o "$TMP/v4"
curl -fsSL https://www.cloudflare.com/ips-v6 -o "$TMP/v6"

python3 - "$TMP/v4" "$TMP/v6" "$SNIP/cloudflare-allowlist-map.conf" <<'PY'
import pathlib, sys
v4, v6, out = map(pathlib.Path, sys.argv[1:])
lines = [
    "# Auto-generated by apply_cloudflare_origin_guard.sh — do not hand-edit",
    "# IMPORTANT: key off $realip_remote_addr (pre-rewrite). Using $remote_addr after",
    "# set_real_ip_from + CF-Connecting-IP makes geo see the browser IP → false 403.",
    "geo $realip_remote_addr $hackme_cf_ok {",
    "  default 0;",
]
for p in (v4, v6):
    for cidr in p.read_text().splitlines():
        cidr = cidr.strip()
        if cidr:
            lines.append(f"  {cidr} 1;")
lines += ["  127.0.0.1 1;", "  ::1 1;", "}", ""]
for p in (v4, v6):
    for cidr in p.read_text().splitlines():
        cidr = cidr.strip()
        if cidr:
            lines.append(f"set_real_ip_from {cidr};")
lines.append("real_ip_header CF-Connecting-IP;")
out.write_text("\n".join(lines) + "\n")
print(f"wrote {out}")
PY

# Deny snippet (literal $ for nginx)
sudo tee "$SNIP/cloudflare-only-443.inc" >/dev/null <<'INC'
# Deny non-Cloudflare (and non-loopback) clients on this :443 vhost.
if ($hackme_cf_ok = 0) { return 403; }
INC

if [[ ! -f /etc/nginx/conf.d/hackme-cloudflare-map.conf ]]; then
  echo 'include /etc/nginx/snippets/cloudflare-allowlist-map.conf;' | sudo tee /etc/nginx/conf.d/hackme-cloudflare-map.conf >/dev/null
fi

if [[ "${APPLY_VHOSTS}" == "1" ]]; then
  for f in /etc/nginx/sites-enabled/hackme-site-domain.conf \
           /etc/nginx/sites-enabled/hackme-explorer-domain.conf \
           /etc/nginx/sites-enabled/hackme-dl-origin.conf; do
    [[ -f "$f" ]] || continue
    if grep -q 'cloudflare-only-443.inc' "$f"; then
      echo "[cf-guard] already present: $f"
      continue
    fi
    sudo cp -a "$f" "$f.bak-cfguard-$(date -u +%Y%m%dT%H%M%SZ)"
    sudo python3 - "$f" <<'PY'
import pathlib, re, sys
p = pathlib.Path(sys.argv[1])
text = p.read_text()
inc = "    include /etc/nginx/snippets/cloudflare-only-443.inc;\n"
if "cloudflare-only-443.inc" in text:
    raise SystemExit(0)
out, inserted = [], 0
for line in text.splitlines(True):
    out.append(line)
    if inserted < 3 and re.search(r"ssl_protocols\s+", line):
        out.append(inc)
        inserted += 1
p.write_text("".join(out))
print(f"[cf-guard] patched {p} inserts={inserted}")
PY
  done
fi

sudo nginx -t
if [[ "${DRY_RUN}" == "1" ]]; then
  echo "[cf-guard] DRY_RUN=1 — not reloading"
else
  sudo systemctl reload nginx
  echo "[cf-guard] nginx reloaded"
fi
echo "[cf-guard] map ready; APPLY_VHOSTS=${APPLY_VHOSTS}"
REMOTE
